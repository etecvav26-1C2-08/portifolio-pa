    # Descrição: Lê um número inteiro e informa se ele é positivo, negativo ou zero.

número = int(input("Digite um número inteiro: "))

if número > 0:
    print("O número e positivo.")
elif número < 0:
    print("O número e negativo.")
else:
    print("O número e zero.")
